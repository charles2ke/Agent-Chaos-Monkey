#!/usr/bin/env node
// Runs one or more chaos suites against a running API and produces a resilience leaderboard.
//
// Usage: node cli/benchmark.mjs <targets.json> [--url http://localhost:5249] [--output results/benchmark]
//        [--timeout-ms 120000]
//
// Each target may declare a `launch` block; the named process is started before the target's suite
// runs and stopped afterwards, so a single manifest can benchmark several agents in one pass.
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { spawn } from 'node:child_process'
import { resolve, join } from 'node:path'

const usage = 'node cli/benchmark.mjs <targets.json> [--url http://localhost:5249] [--output results/benchmark] [--timeout-ms 120000]'

export function summarize(targetName, platform, notes, suiteResult) {
  const results = suiteResult.results ?? []
  const counts = { pass: 0, fail: 0, inconclusive: 0 }
  const dimensions = new Map()
  let falseSuccessAfter401 = 0
  let falseSuccess = 0
  for (const result of results) {
    counts[result.outcome] = (counts[result.outcome] ?? 0) + 1
    for (const run of result.runs ?? []) {
      // Assertion results carry the evaluator's detail text rather than the assertion kind, so an
      // unsupported success claim is identified by the evidence evaluator's wording.
      const dishonest = (run.assertions ?? []).some((assertion) =>
        assertion.outcome === 'fail' && /claimed success/i.test(assertion.detail ?? ''))
      const unauthorized = (run.trace ?? []).some((call) => call.statusCode === 401)
      if (dishonest) falseSuccess++
      if (dishonest && unauthorized) falseSuccessAfter401++
      for (const dimension of run.dimensions ?? []) {
        const current = dimensions.get(dimension.name) ?? { pass: 0, fail: 0, inconclusive: 0 }
        current[dimension.outcome] = (current[dimension.outcome] ?? 0) + 1
        dimensions.set(dimension.name, current)
      }
    }
  }
  const scored = counts.pass + counts.fail
  return {
    target: targetName,
    platform,
    notes,
    tests: results.length,
    passed: counts.pass,
    failed: counts.fail,
    inconclusive: counts.inconclusive,
    resilienceScore: scored === 0 ? null : Math.round((counts.pass / scored) * 100),
    falseSuccessClaims: falseSuccess,
    falseSuccessAfterUnauthorized: falseSuccessAfter401,
    dimensions: Object.fromEntries(dimensions),
  }
}

export function renderLeaderboard(rows, generatedAt) {
  const header = ['| Agent | Platform | Tests | Passed | Failed | Inconclusive | Resilience score | False success claims |',
    '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
  const body = [...rows]
    .sort((a, b) => (b.resilienceScore ?? -1) - (a.resilienceScore ?? -1))
    .map((row) => `| ${row.target} | ${row.platform} | ${row.tests} | ${row.passed} | ${row.failed} | ` +
      `${row.inconclusive} | ${row.resilienceScore === null ? 'n/a' : `${row.resilienceScore}%`} | ${row.falseSuccessClaims} |`)
  const claimed = rows.filter((row) => row.falseSuccessAfterUnauthorized > 0).length
  return [
    '<!-- Generated by cli/benchmark.mjs. Do not edit by hand. -->',
    `_Measured ${generatedAt}._`,
    '',
    ...header,
    ...body,
    '',
    `**${claimed} of ${rows.length} benchmarked agents reported success to the user after the connector returned HTTP 401.**`,
    '',
  ].join('\n')
}

async function waitForPort(url, timeoutMs) {
  const deadline = Date.now() + timeoutMs
  do {
    try {
      await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{}' })
      return true
    } catch {
      if (Date.now() >= deadline) return false
      await new Promise((done) => setTimeout(done, 200))
    }
  } while (Date.now() < deadline)
  return false
}

async function runTarget(target, baseUrl, timeoutMs) {
  let child = null
  let exited = null
  if (target.launch) {
    if (target.launch.command !== 'node') throw new Error('Only the node command may be launched by the benchmark.')
    // A process already serving that address would silently benchmark the wrong agent.
    if (target.launch.readyUrl && await waitForPort(target.launch.readyUrl, 0)) {
      throw new Error(`${target.launch.readyUrl} is already in use; stop it before benchmarking ${target.id}.`)
    }
    child = spawn('node', target.launch.args ?? [], { stdio: 'ignore' })
    exited = new Promise((done) => child.once('exit', done))
    let failed = false
    exited.then(() => { failed = true })
    if (target.launch.readyUrl && !(await waitForPort(target.launch.readyUrl, 10_000))) {
      child.kill()
      throw new Error(`Target ${target.id} did not start.`)
    }
    // A port left in use by a previous target would silently serve the wrong agent.
    if (failed) throw new Error(`Target ${target.id} exited before it could serve a request.`)
  }
  try {
    const suite = JSON.parse(await readFile(resolve(target.suite), 'utf8'))
    const response = await fetch(new URL('/api/lab/suite', baseUrl), {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ tests: suite.tests.map((test) => ({ definition: test.definition })) }),
      signal: AbortSignal.timeout(timeoutMs),
    })
    if (!response.ok) throw new Error(`Suite request failed with HTTP ${response.status}.`)
    return summarize(target.name, target.platform ?? 'unknown', target.notes ?? '', await response.json())
  } finally {
    if (child) {
      child.kill()
      // Wait for the port to be released before the next target starts.
      await Promise.race([exited, new Promise((done) => setTimeout(done, 5_000))])
    }
  }
}

async function main() {
  const args = process.argv.slice(2)
  const manifestPath = args.shift()
  let baseUrl = 'http://localhost:5249'
  let output = 'results/benchmark'
  let timeoutMs = 120_000
  if (!manifestPath || manifestPath.startsWith('--')) throw new Error(usage)
  while (args.length) {
    const flag = args.shift()
    if (flag === '--url' && args.length) baseUrl = args.shift()
    else if (flag === '--output' && args.length) output = args.shift()
    else if (flag === '--timeout-ms' && args.length) timeoutMs = Number(args.shift())
    else throw new Error(usage)
  }
  const url = new URL(baseUrl)
  if (url.username || url.password || url.search || url.hash ||
      (url.protocol !== 'https:' && !(url.protocol === 'http:' && ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)))) {
    throw new Error('API URL must use HTTPS (or loopback HTTP), without credentials, query, or fragment.')
  }
  if (!Number.isInteger(timeoutMs) || timeoutMs < 1 || timeoutMs > 600_000) {
    throw new Error('Timeout must be between 1 and 600000 ms.')
  }

  const manifest = JSON.parse(await readFile(resolve(manifestPath), 'utf8'))
  const rows = []
  for (const target of manifest.targets ?? []) {
    process.stdout.write(`Benchmarking ${target.name}... `)
    const row = await runTarget(target, baseUrl, timeoutMs)
    rows.push(row)
    console.log(`${row.passed}/${row.tests} passed`)
  }
  const generatedAt = new Date().toISOString()
  const directory = resolve(output)
  await mkdir(directory, { recursive: true })
  await writeFile(join(directory, 'benchmark.json'), JSON.stringify({ schemaVersion: 1, generatedAt, targets: rows }, null, 2))
  await writeFile(join(directory, 'leaderboard.md'), renderLeaderboard(rows, generatedAt))
  console.log(`Wrote ${join(directory, 'benchmark.json')} and ${join(directory, 'leaderboard.md')}.`)
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  main().catch((error) => {
    console.error(error.message)
    process.exit(2)
  })
}
